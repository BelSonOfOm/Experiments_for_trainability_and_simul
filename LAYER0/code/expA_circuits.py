"""expA_circuits.py — experiment A, circuit side: the TFIM circuit built by Charbel's generator rule, on the
10 periodic TFIM problems.

WHAT THIS FILE DOES (plan approved by Charbel, 2 Nov 2026, 19:11-19:25; see LAYER0/LOG.md)
  1. load_tfim         reused unchanged; TRAIN for training and variance, TEST for accuracy;
  2. dla_dimension     dimension of the Lie algebra generated by i*sum ZZ (ring) and i*sum X, by closure under
                       commutators written with Pauli strings (reaches n = 12; code/tools/dla_check.py is dense, n <= 6);
  3. depths            L* = ceil(dim g / 2) rounds (two angles per round); below = ceil(L*/2), above = 2 L* (Charbel);
  4. apply_circuit     exact statevector, all inputs at once; each round: e^{-i theta sum ZZ} (diagonal phases),
                       then e^{-i phi X} on every qubit;
  5. outputs           f = <psi|U^dag O U|psi> for O = a sum X/n + b sum ZZ/n: (a,b) = (1,0) "X", (0,1) "ZZ",
                       (1/2,1/2) "fixed", trained "trained" (a, b started uniformly in [0, 2 pi) like the angles);
  6. loss              mean over TRAIN of (f - y)^2;
  7. gradient          exact, adjoint method (Jones & Gacon 2020);
  8. train             Adam (Kingma & Ba 2015: rate 0.001, beta1 0.9, beta2 0.999, eps 1e-8), 500 steps, one run,
                       angles started uniformly in [0, 2 pi); loss curve, TRAIN and TEST accuracy (sign of f vs y);
  9. variance          over 500 random starts: variance of dL/d(first angle) (McClean et al. 2018) and the mean
                       over TRAIN inputs of the variance of f (the quantity of Ragone et al. 2024);
 10. summary           CSV tables and figures.
Checks (run first): Pauli-string DLA = dense dla_check at n = 4, 6; adjoint gradient = central finite differences
within 1e-6; all angles 0 gives f = <X> of layer zero within 1e-12 for O = sum X/n.
SPEED (exact, no approximation): the inputs, both generators and both observables are invariant under shift, mirror
and global flip, so the computation runs in the subspace of states invariant under all of them (SymSpace); checks:
every input is constant on the orbits of that group (1e-12) and SymSpace reproduces the full simulation (1e-10).
"""
