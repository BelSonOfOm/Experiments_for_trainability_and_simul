# ------------------------------------------------------------------ 2. Lie algebra (Pauli strings)
# single-qubit products: P*Q = phase * R, codes 0=I 1=X 2=Y 3=Z
_MUL = {}
for p in range(4):
    _MUL[(0, p)] = (1, p); _MUL[(p, 0)] = (1, p); _MUL[(p, p)] = (1, 0)
for a, b, c in ((1, 2, 3), (2, 3, 1), (3, 1, 2)):
    _MUL[(a, b)] = (1j, c); _MUL[(b, a)] = (-1j, c)


def pauli_mul(p: tuple, q: tuple) -> tuple:
    """WHAT: P*Q = phase * R for Pauli strings P, Q (tuples of codes)."""
    ph, r = 1, []
    for a, b in zip(p, q):
        f, c = _MUL[(a, b)]
        ph *= f; r.append(c)
    return ph, tuple(r)


def commutator(A: dict, B: dict) -> dict:
    """WHAT: [iA, iB] written as i*C with C real-combination of Pauli strings; A, B are dicts {string: real coeff}
    standing for iA, iB. For Hermitian Pauli strings P, Q: [iP, iQ] = -(PQ - QP) = -2PQ if they anticommute, else 0;
    PQ = (i s) R, so [iP, iQ] = i * (-2 s) R."""
    C = {}
    for p, a in A.items():
        for q, b in B.items():
            ph, r = pauli_mul(p, q)
            if abs(ph.imag) > 0.5:                     # anticommuting pair: PQ = i s R
                s = ph.imag
                C[r] = C.get(r, 0.0) - 2.0 * s * a * b
    return {k: v for k, v in C.items() if abs(v) > 1e-12}


def lie_closure(gens: list, cap: int = 20000) -> int:
    """WHAT: dimension of the real Lie algebra spanned by the generators and all nested commutators.
    HOW: Gram-Schmidt in the (orthonormal) Pauli-string basis; commutators of every new element with all earlier."""
    basis = []

    def add(v):
        v = dict(v)
        for b in basis:
            d = sum(v.get(k, 0.0) * x for k, x in b.items())
            if d:
                for k, x in b.items():
                    v[k] = v.get(k, 0.0) - d * x
        nrm = math.sqrt(sum(x * x for x in v.values()))
        if nrm > 1e-9:
            basis.append({k: x / nrm for k, x in v.items() if abs(x / nrm) > 1e-13})
            return True
        return False

    for g in gens:
        add(g)
    i = 0
    while i < len(basis):
        for j in range(i):
            c = commutator(basis[i], basis[j])
            if c:
                add(c)
        i += 1
        if len(basis) > cap:
            raise RuntimeError("Lie algebra larger than cap")
    return len(basis)


def tfim_generators(n: int) -> list:
    """WHAT: the two generators of Charbel's rule on a periodic chain: sum_i Z_i Z_{i+1} (ring) and sum_i X_i."""
    zz, x = {}, {}
    for i in range(n):
        s = [0] * n; s[i] = 3; s[(i + 1) % n] = 3; zz[tuple(s)] = 1.0
        s = [0] * n; s[i] = 1; x[tuple(s)] = 1.0
    return [zz, x]


def dla_dimension(n: int) -> int:
    return lie_closure(tfim_generators(n))


def depths(dim: int) -> dict:
    """WHAT: below, at and above the threshold L* = ceil(dim / 2) (Charbel: half and double L*)."""
    L = math.ceil(dim / 2)
    return {"below": math.ceil(L / 2), "at": L, "above": 2 * L}


# ------------------------------------------------------------------ 4-5. circuit and outputs
def zz_diagonal(n: int) -> np.ndarray:
    """WHAT: diagonal of sum_i Z_i Z_{i+1} on the ring, qubit k = bit k of the basis index."""
    idx = np.arange(2 ** n)
    z = 1 - 2 * ((idx[:, None] >> np.arange(n)) & 1)
    return np.sum(z * np.roll(z, -1, axis=1), axis=1).astype(float)


def apply_x_all(psi: np.ndarray, phi: float, n: int) -> np.ndarray:
    """WHAT: e^{-i phi X} on every qubit (cos phi - i sin phi X_k, qubit by qubit), on a batch (N, 2^n)."""
    c, s = math.cos(phi), math.sin(phi)
    N = psi.shape[0]
    for k in range(n):
        v = psi.reshape(N, 2 ** (n - k - 1), 2, 2 ** k)
        psi = (c * v - 1j * s * v[:, :, ::-1, :]).reshape(N, -1)
    return psi


def xsum(psi: np.ndarray, n: int) -> np.ndarray:
    """WHAT: (sum_k X_k) psi on a batch."""
    N = psi.shape[0]
    out = np.zeros_like(psi)
    for k in range(n):
        out += psi.reshape(N, 2 ** (n - k - 1), 2, 2 ** k)[:, :, ::-1, :].reshape(N, -1)
    return out


def apply_circuit(psi: np.ndarray, angles: np.ndarray, n: int, zz: np.ndarray) -> np.ndarray:
    """WHAT: U psi with U = prod over rounds of e^{-i phi_l sum X} e^{-i theta_l sum ZZ}; angles[l] = (theta_l, phi_l)."""
    psi = psi.astype(complex)
    for th, ph in angles:
        psi = psi * np.exp(-1j * th * zz)
        psi = apply_x_all(psi, ph, n)
    return psi


def outputs(psi_out: np.ndarray, n: int, zz: np.ndarray) -> tuple:
    """WHAT: (f_X, f_ZZ) = (<sum X>/n, <sum ZZ>/n) of each output state."""
    fx = np.real(np.sum(np.conj(psi_out) * xsum(psi_out, n), axis=1)) / n
    fzz = np.real(np.sum(np.abs(psi_out) ** 2 * zz, axis=1)) / n
    return fx, fzz


# ------------------------------------------------------------------ 6-7. loss and exact gradient
def run_circuit(psi, angles, sp):
    """WHAT: U psi in the space sp (FullSpace or SymSpace); round l: e^{-i theta_l sum ZZ}, then e^{-i phi_l sum X}."""
    for th, ph in angles:
        psi = psi * np.exp(-1j * th * sp.zz)
        psi = sp.apply_x(psi, ph)
    return psi


def sp_outputs(psi, sp):
    """WHAT: (<sum X>/n, <sum ZZ>/n) of each state in the space sp."""
    fx = np.real(np.sum(np.conj(psi) * sp.xsum(psi), axis=1)) / sp.n
    fzz = np.real(np.sum(np.abs(psi) ** 2 * sp.zz, axis=1)) / sp.n
    return fx, fzz


def loss_and_grad(psi0, y, angles, ab, sp):
    """WHAT: L = mean (f - y)^2 with f = a f_X + b f_ZZ; returns L, dL/dangles (L, 2), dL/d(a, b), f.
    HOW: adjoint method: lambda = sum_i r_i O phi_i with r_i = 2 (f_i - y_i)/N, propagated backwards; for a gate
    e^{-i alpha H}, dL/dalpha = 2 Im <lambda|H|phi> at that gate (Jones & Gacon 2020). psi0 is already embedded."""
    a, b = ab
    n = sp.n
    phi = run_circuit(psi0, angles, sp)
    fx, fzz = sp_outputs(phi, sp)
    f = a * fx + b * fzz
    N = len(y)
    r = 2.0 * (f - y) / N
    loss = float(np.mean((f - y) ** 2))
    lam = r[:, None] * (a * sp.xsum(phi) / n + b * sp.zz * phi / n)
    g_ab = np.array([np.sum(r * fx), np.sum(r * fzz)])
    g = np.zeros_like(angles, dtype=float)
    for l in range(len(angles) - 1, -1, -1):
        th, ph = angles[l]
        g[l, 1] = 2.0 * np.imag(np.sum(np.conj(lam) * sp.xsum(phi)))
        phi = sp.apply_x(phi, -ph); lam = sp.apply_x(lam, -ph)
        g[l, 0] = 2.0 * np.imag(np.sum(np.conj(lam) * sp.zz * phi))
        phi = phi * np.exp(1j * th * sp.zz); lam = lam * np.exp(1j * th * sp.zz)
    return loss, g, g_ab, f


# ------------------------------------------------------------------ 8. training
def train(psi0, y, psi_test, test_y, L, obs, sp, rng):
    """WHAT: Adam on the angles (and on a, b for "trained"); returns the loss curve and accuracies."""
    angles = rng.uniform(0, 2 * math.pi, size=(L, 2))
    ab = np.array(rng.uniform(0, 2 * math.pi, size=2) if OBS[obs] is None else OBS[obs], dtype=float)
    params = [angles, ab]
    m = [np.zeros_like(p) for p in params]; v = [np.zeros_like(p) for p in params]
    curve = []
    for t in range(1, STEPS + 1):
        loss, g, gab, _ = loss_and_grad(psi0, y, params[0], params[1], sp)
        curve.append(loss)
        grads = [g, gab if OBS[obs] is None else np.zeros(2)]
        for k in range(2):
            m[k] = BETA1 * m[k] + (1 - BETA1) * grads[k]
            v[k] = BETA2 * v[k] + (1 - BETA2) * grads[k] ** 2
            mh = m[k] / (1 - BETA1 ** t); vh = v[k] / (1 - BETA2 ** t)
            params[k] = params[k] - LR * mh / (np.sqrt(vh) + EPS)
    final, _, _, f_tr = loss_and_grad(psi0, y, params[0], params[1], sp)
    curve.append(final)
    fx, fzz = sp_outputs(run_circuit(psi_test, params[0], sp), sp)
    f_te = params[1][0] * fx + params[1][1] * fzz
    acc = lambda f, yy: float(np.mean(np.where(f > 0, 1, -1) == yy))
    return {"curve": np.array(curve), "train_acc": acc(f_tr, y), "test_acc": acc(f_te, test_y),
            "a": float(params[1][0]), "b": float(params[1][1])}


# ------------------------------------------------------------------ 9. variance
def variance(psi0, y, L, obs, sp, rng):
    """WHAT: over STARTS random starts: Var of dL/d(first angle), and mean over inputs of Var of f."""
    g1, F = [], []
    for _ in range(STARTS):
        angles = rng.uniform(0, 2 * math.pi, size=(L, 2))
        ab = rng.uniform(0, 2 * math.pi, size=2) if OBS[obs] is None else OBS[obs]
        _, g, _, f = loss_and_grad(psi0, y, angles, ab, sp)
        g1.append(g[0, 0]); F.append(f)
    return {"var_grad_first": float(np.var(g1)), "mean_var_f": float(np.mean(np.var(np.array(F), axis=0)))}


# ------------------------------------------------------------------ exact symmetric subspace
class FullSpace:
    """The full 2^n-dimensional simulation (functions above)."""
    def __init__(self, n):
        self.n, self.zz = n, zz_diagonal(n)
    def embed(self, states):
        return np.asarray(states, dtype=complex)
    def apply_x(self, psi, phi):
        return apply_x_all(psi, phi, self.n)
    def xsum(self, psi):
        return xsum(psi, self.n)


class SymSpace:
    """WHAT: the subspace of states invariant under shift, mirror and global flip of the ring.
    HOW: orbits of the 2^n basis strings under that group; orthonormal basis |O> = |O|^{-1/2} sum_{s in O} |s>;
    sum ZZ is constant on each orbit (diagonal); sum X becomes a real symmetric d x d matrix M = V D V^T, so
    e^{-i phi sum X} = V e^{-i phi D} V^T. Exact for invariant inputs, since every operator here commutes with the group."""
    def __init__(self, n):
        self.n = n
        N = 2 ** n
        idx = np.arange(N)
        bits = (idx[:, None] >> np.arange(n)) & 1
        images = []
        for sh in range(n):
            for mir in (False, True):
                b = np.roll(bits, sh, axis=1)
                if mir:
                    b = b[:, ::-1]
                for fl in (0, 1):
                    images.append(((b ^ fl) << np.arange(n)).sum(axis=1))
        rep = np.min(np.stack(images), axis=0)              # orbit label = smallest image
        labels, self.orbit = np.unique(rep, return_inverse=True)
        d = len(labels)
        size = np.bincount(self.orbit, minlength=d).astype(float)
        P = np.zeros((N, d))
        P[idx, self.orbit] = 1.0 / np.sqrt(size[self.orbit])
        self.P = P
        zz_full = zz_diagonal(n)
        self.zz = np.array([zz_full[self.orbit == o][0] for o in range(d)])
        M = P.T @ np.real(xsum(P.T.astype(complex), n)).T      # <O| sum X |O'>
        self.M = 0.5 * (M + M.T)
        self.D, self.V = np.linalg.eigh(self.M)
    def embed(self, states):
        """Coordinates of invariant states in the orbit basis; raises if a state is not invariant."""
        st = np.asarray(states, dtype=float)
        c = st @ self.P
        back = c @ self.P.T
        err = float(np.max(np.abs(back - st)))
        if err > 1e-12:
            raise ValueError(f"an input is not invariant under shift, mirror and flip (worst {err:.1e})")
        return c.astype(complex)
    def apply_x(self, psi, phi):
        return ((psi @ self.V) * np.exp(-1j * phi * self.D)) @ self.V.T
    def xsum(self, psi):
        return psi @ self.M


# ------------------------------------------------------------------ checks
def checks() -> None:
    sys.path.insert(0, str(HERE.parents[1] / "code" / "tools"))
    import dla_check as dc
    for n in (4, 6):
        Xm, Zm = dc.X, dc.Z
        SZZ = sum(dc.op(n, {i: Zm, (i + 1) % n: Zm}) for i in range(n))
        SX = sum(dc.op(n, {i: Xm}) for i in range(n))
        dense, pauli = dc.closure([SZZ, SX]), dla_dimension(n)
        assert dense == pauli, f"DLA n={n}: dense {dense} vs Pauli {pauli}"
        print(f"check DLA n={n}: dense {dense} = Pauli {pauli}")
    rng = np.random.default_rng(0)
    t = [t for t in tfim_task_ids() if describe(t)["boundary"] == "periodic" and describe(t)["n"] == 4][0]
    d = load_tfim(t); tr = d["split"] == "TRAIN"
    yy, n = d["y"][tr][:20].astype(float), 4
    sp = FullSpace(n); st = sp.embed(d["states"][tr][:20])
    ang = rng.uniform(0, 2 * math.pi, size=(3, 2)); ab = rng.uniform(0, 2 * math.pi, size=2)
    _, g, gab, _ = loss_and_grad(st, yy, ang, ab, sp)
    h, worst = 1e-5, 0.0
    for idx in np.ndindex(ang.shape):
        e = np.zeros_like(ang); e[idx] = h
        fd = (loss_and_grad(st, yy, ang + e, ab, sp)[0] - loss_and_grad(st, yy, ang - e, ab, sp)[0]) / (2 * h)
        worst = max(worst, abs(fd - g[idx]))
    for k in range(2):
        e = np.zeros(2); e[k] = h
        fd = (loss_and_grad(st, yy, ang, ab + e, sp)[0] - loss_and_grad(st, yy, ang, ab - e, sp)[0]) / (2 * h)
        worst = max(worst, abs(fd - gab[k]))
    assert worst <= 1e-6, f"gradient check worst {worst:.1e}"
    print(f"check gradient: worst |adjoint - finite difference| = {worst:.1e}")
    worst, worst_sym = 0.0, 0.0
    for t in [t for t in tfim_task_ids() if describe(t)["boundary"] == "periodic"]:
        d = load_tfim(t); n = d["n"]
        full, sym = FullSpace(n), SymSpace(n)
        st5 = d["states"][:5]
        fx, _ = sp_outputs(run_circuit(full.embed(st5), np.zeros((2, 2)), full), full)
        X0 = np.array([qubit_states(s, n)[0, 0] for s in st5])
        worst = max(worst, float(np.max(np.abs(fx - X0))))
        sym.embed(d["states"])                               # raises if an input is not invariant
        if n <= 8:
            tr = d["split"] == "TRAIN"; y8 = d["y"][tr][:30].astype(float)
            a8 = rng.uniform(0, 2 * math.pi, size=(4, 2)); b8 = rng.uniform(0, 2 * math.pi, size=2)
            A = loss_and_grad(full.embed(d["states"][tr][:30]), y8, a8, b8, full)
            B = loss_and_grad(sym.embed(d["states"][tr][:30]), y8, a8, b8, sym)
            diff = max(abs(A[0] - B[0]), np.max(np.abs(A[1] - B[1])), np.max(np.abs(A[2] - B[2])), np.max(np.abs(A[3] - B[3])))
            worst_sym = max(worst_sym, float(diff))
    assert worst <= 1e-12, f"identity check worst {worst:.1e}"
    assert worst_sym <= 1e-10, f"symmetric subspace check worst {worst_sym:.1e}"
    print(f"check identity: worst |f_X - <X> of layer zero| = {worst:.1e}")
    print(f"check inputs invariant: every periodic input lies in the symmetric subspace (1e-12)")
    print(f"check symmetric subspace = full simulation (n <= 8): worst {worst_sym:.1e}")


def main() -> None:
    """WHAT: checks, then for each periodic problem, observable and depth: one training run and the variance.
    Seeds: numpy default_rng([n, window index, observable index, depth index]) for reproducibility.
    Outputs in results/expA_circuits/: runs.csv (one row per configuration), curves.npz (loss curves)."""
    import pandas as pd
    checks()
    OUT.mkdir(parents=True, exist_ok=True)
    rows, curves = [], {}
    tasks = sorted([t for t in tfim_task_ids() if describe(t)["boundary"] == "periodic"],
                   key=lambda t: (describe(t)["n"], describe(t)["window"]))
    for t in tasks:
        info = describe(t)
        n = info["n"]
        d = load_tfim(t)
        sp = SymSpace(n)
        tr, te = d["split"] == "TRAIN", d["split"] == "TEST"
        psi_tr, psi_te = sp.embed(d["states"][tr]), sp.embed(d["states"][te])
        y_tr, y_te = d["y"][tr].astype(float), d["y"][te].astype(float)
        dim = dla_dimension(n)
        for oi, obs in enumerate(OBS):
            for di, (label, L) in enumerate(depths(dim).items()):
                t0 = time.time()
                seed = [n, ("far", "near").index(info["window"]), oi, di]
                tr_res = train(psi_tr, y_tr, psi_te, y_te, L, obs, sp, np.random.default_rng(seed + [0]))
                var_res = variance(psi_tr, y_tr, L, obs, sp, np.random.default_rng(seed + [1]))
                key = f"{n}_{info['window']}_{obs}_{label}"
                curves[key] = tr_res["curve"]
                rows.append({"task_id": t, **info, "dim_g": dim, "observable": obs, "depth": label, "L": L,
                             "loss_start": float(tr_res["curve"][0]), "loss_end": float(tr_res["curve"][-1]),
                             "train_acc": tr_res["train_acc"], "test_acc": tr_res["test_acc"],
                             "a_end": tr_res["a"], "b_end": tr_res["b"], **var_res,
                             "seconds": round(time.time() - t0, 1)})
                print(f"{key}: loss {rows[-1]['loss_start']:.3f} -> {rows[-1]['loss_end']:.3f}, "
                      f"acc train {rows[-1]['train_acc']:.2f} test {rows[-1]['test_acc']:.2f}, "
                      f"Var dL/dtheta1 {var_res['var_grad_first']:.2e}, Var f {var_res['mean_var_f']:.2e}", flush=True)
        pd.DataFrame(rows).to_csv(OUT / "runs.csv", index=False)
        np.savez(OUT / "curves.npz", **curves)
    print("done")


if __name__ == "__main__":
    if len(sys.argv) == 1:
        main()
    elif sys.argv[1] == "--checks":
        checks()
